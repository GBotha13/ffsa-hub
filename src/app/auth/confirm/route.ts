import { createServerClient } from "@supabase/ssr";
import { type EmailOtpType } from "@supabase/supabase-js";
import { cookies } from "next/headers";
import { NextResponse, type NextRequest } from "next/server";

export async function GET(request: NextRequest) {
  const { searchParams } = new URL(request.url);
  const token_hash = searchParams.get("token_hash");
  const type = searchParams.get("type") as EmailOtpType | null;
  const code = searchParams.get("code");

  const cookieStore = await cookies();

  const supabase = createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        getAll() {
          return cookieStore.getAll();
        },
        setAll(cookiesToSet) {
          cookiesToSet.forEach(({ name, value, options }) => {
            cookieStore.set(name, value, options);
          });
        },
      },
    }
  );

  // Handle PKCE flow (code exchange) — used by invite links
  if (code) {
    const { error } = await supabase.auth.exchangeCodeForSession(code);
    if (error) {
      return NextResponse.redirect(
        new URL(`/login?error=invite_expired`, request.url)
      );
    }
    // Successfully authenticated — redirect to onboarding
    return NextResponse.redirect(new URL("/onboarding", request.url));
  }

  // Handle OTP flow (token_hash + type) — used by magic links / email verification
  if (token_hash && type) {
    const { error } = await supabase.auth.verifyOtp({ token_hash, type });
    if (error) {
      return NextResponse.redirect(
        new URL(`/login?error=invite_expired`, request.url)
      );
    }
    // Successfully verified — redirect to onboarding
    return NextResponse.redirect(new URL("/onboarding", request.url));
  }

  // Neither code nor token_hash provided
  return NextResponse.redirect(new URL("/login?error=invalid_link", request.url));
}
